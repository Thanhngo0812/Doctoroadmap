"""SA-22 step 1, zero network calls: choose the sample and compute the dry-run estimate.

Sample (report 5.2): per book K concepts that the cloze rules can hollow out, taken from whole modules.
  1. modules of a book are shuffled with a fixed seed;
  2. whole modules are added until they hold at least K cloze-eligible concepts (all concepts of a chosen module are
     generated by branch A, eligible or not, so rejected candidates and coverage are measured on the whole module);
  3. K target concepts are drawn with a fixed seed from the eligible concepts of the chosen modules.
Writes tmp/sa22/plan.json. Prints counts and the estimate only.
"""
from __future__ import annotations

import json
import random
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from doc2roadmap.domain.phase_b_pricing import estimate_cost  # noqa: E402

from sa22_common import MODEL_ID, OUT, PINS, SEEDS, STRATA, load_graphs, use_case  # noqa: E402

CAP_USD = 2.0


def cloze_items(graph, concept):
    """Cloze bank of one concept under quiz-local-rules-v4, plus the rejection rows (no model, no network)."""
    uc = use_case(graph, None, None, f'plan:{concept["node_id"]}', llm=False)
    context = uc._context(concept.get('module_id'), concept)
    return uc._cloze_bank(concept, context), uc, context


def main():
    graphs = load_graphs()
    plan = {'seeds': SEEDS, 'strata': STRATA, 'pins': PINS, 'books': {}}
    total = Counter()
    estimate = {'generation': 0.0, 'verifier': 0.0}
    for doc_id, graph in graphs.items():
        k = STRATA[doc_id]
        modules = sorted(graph.modules.values(), key=lambda m: m.get('index', 0))
        order = random.Random(f"{SEEDS['sample']}:{doc_id}").sample([m['module_id'] for m in modules], len(modules))
        info = {}
        for module in modules:
            rows = []
            for node_id in module['node_ids']:
                node = graph.nodes.get(node_id)
                if not node or not node.get('learnable', True):
                    continue
                concept = {**node, 'node_id': node_id}
                bank, uc, context = cloze_items(graph, concept)
                rows.append({'node_id': node_id, 'eligible': bool(bank), 'cloze_reasons':
                             sorted({r['reason'] for r in uc.captured}) if not bank else []})
            info[module['module_id']] = rows
        chosen, eligible_count = [], 0
        for module_id in order:
            if eligible_count >= k:
                break
            chosen.append(module_id)
            eligible_count += sum(r['eligible'] for r in info[module_id])
        pool = sorted(r['node_id'] for module_id in chosen for r in info[module_id] if r['eligible'])
        targets = sorted(random.Random(f"{SEEDS['sample']}:t:{doc_id}").sample(pool, min(k, len(pool))))
        concepts = [r['node_id'] for module_id in chosen for r in info[module_id]]
        book = {'graph_version': graph.graph_version, 'k': k, 'modules_total': len(modules),
                'modules_chosen': chosen, 'concepts_in_chosen_modules': concepts, 'targets': targets,
                'eligible_in_chosen_modules': len(pool),
                'eligible_in_book': sum(r['eligible'] for rows in info.values() for r in rows),
                'learnable_in_book': sum(len(rows) for rows in info.values())}
        # Dry-run: same upper bound as QuizUseCase.make_quiz(dry_run=True) = 2 attempts per call kind at the output caps.
        gen_in = gen_out = ver_in = ver_out = calls = 0
        for node_id in concepts:
            concept = {**graph.nodes[node_id], 'node_id': node_id}
            uc = use_case(graph, None, None, f'plan-est:{node_id}', llm=False)
            context = uc._context(concept.get('module_id'), concept)
            a, b, c, d = uc._bank_estimate_token_breakdown(context)
            gen_in += a; gen_out += b; ver_in += c; ver_out += d; calls += 4
        gen_cost, ver_cost = estimate_cost(MODEL_ID, gen_in, gen_out), estimate_cost(MODEL_ID, ver_in, ver_out)
        book.update(estimated_calls_upper=calls, estimated_usd_upper=round(gen_cost + ver_cost, 4))
        estimate['generation'] += gen_cost
        estimate['verifier'] += ver_cost
        plan['books'][doc_id] = book
        total.update(modules=len(chosen), concepts=len(concepts), targets=len(targets), calls=calls)
        print(doc_id, {k2: (len(v) if isinstance(v, list) else v) for k2, v in book.items() if k2 != 'seeds'}, flush=True)
    plan['totals'] = dict(total)
    plan['estimate_usd_upper'] = round(sum(estimate.values()), 4)
    plan['estimate_parts'] = {k: round(v, 4) for k, v in estimate.items()}
    plan['cap_usd'] = CAP_USD
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'plan.json').write_text(json.dumps(plan, ensure_ascii=False, indent=1, sort_keys=True) + '\n', encoding='utf-8')
    print(json.dumps({'totals': plan['totals'], 'estimate_usd_upper': plan['estimate_usd_upper'], 'cap_usd': CAP_USD,
                      'within_cap': plan['estimate_usd_upper'] <= CAP_USD, 'network_calls': 0}))


if __name__ == '__main__':
    main()
